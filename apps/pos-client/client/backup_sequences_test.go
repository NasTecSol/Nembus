// Uses a disposable database; never restores over the database in the supplied DSN.
func TestRestoreRepairsSequencesBeforePermissionMigration(t *testing.T) {
	ctx, testURL, config := newRestoreTestDatabase(t)
	fixture := `
CREATE TABLE product_variants (id SERIAL PRIMARY KEY);
INSERT INTO product_variants (id) VALUES (7);
CREATE TABLE menu_items (id SERIAL PRIMARY KEY, product_variant_id INTEGER, name TEXT);
INSERT INTO menu_items (id, product_variant_id, name) VALUES
    (20, 11, 'Missing variant one'), (13, 14, 'Missing variant two'),
    (21, 7, 'Valid variant'), (22, NULL, 'No variant');
ALTER TABLE ONLY public.menu_items
    ADD CONSTRAINT menu_items_product_variant_id_fkey FOREIGN KEY (product_variant_id) REFERENCES public.product_variants(id) ON DELETE SET NULL;
CREATE TABLE roles (id SERIAL PRIMARY KEY, code TEXT UNIQUE);
CREATE TABLE permissions (id SERIAL PRIMARY KEY, name TEXT, code TEXT UNIQUE, description TEXT);
CREATE TABLE role_permissions (id SERIAL PRIMARY KEY, role_id INTEGER REFERENCES roles(id), permission_id INTEGER REFERENCES permissions(id), UNIQUE(role_id, permission_id));
INSERT INTO roles (id, code) VALUES (1, 'admin'), (2, 'store_manager');
INSERT INTO permissions (id, name, code) VALUES (10, 'Other', 'other'), (100, 'Enroll', 'biometrics.enroll');
INSERT INTO role_permissions (id, role_id, permission_id) VALUES (1, 1, 10), (2, 2, 10);
SELECT setval('permissions_id_seq', 500, true);
SELECT setval('role_permissions_id_seq', 1, false);
CREATE TABLE empty_rows (id SERIAL PRIMARY KEY);
CREATE TABLE ahead_rows (id SERIAL PRIMARY KEY);
INSERT INTO ahead_rows (id) VALUES (3);
SELECT setval('ahead_rows_id_seq', 100, true);
CREATE TABLE equal_rows (id SERIAL PRIMARY KEY);
INSERT INTO equal_rows (id) VALUES (1);
CREATE SCHEMA staging;
CREATE TABLE staging.identity_rows (row_number BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);
INSERT INTO staging.identity_rows (row_number) VALUES (40);
CREATE TABLE "Odd table" ("Odd ID" SERIAL PRIMARY KEY);
INSERT INTO "Odd table" ("Odd ID") VALUES (12);
`
	file := filepath.Join(t.TempDir(), "backup.sql")
	if err := os.WriteFile(file, []byte(fixture), 0600); err != nil {
		t.Fatal(err)
	}
	if err := restoreSQL(file, testURL.String()); err != nil {
		t.Fatal(err)
	}
	conn, err := pgx.ConnectConfig(ctx, config)
	if err != nil {
		t.Fatal(err)
	}
	defer conn.Close(ctx)
	var preservedMenus, clearedLinks, validLink int
	if err := conn.QueryRow(ctx, "SELECT count(*) FROM menu_items").Scan(&preservedMenus); err != nil {
		t.Fatal(err)
	}
	if err := conn.QueryRow(ctx, "SELECT count(*) FROM menu_items WHERE id IN (13, 20) AND product_variant_id IS NULL").Scan(&clearedLinks); err != nil {
		t.Fatal(err)
	}
	if err := conn.QueryRow(ctx, "SELECT product_variant_id FROM menu_items WHERE id = 21").Scan(&validLink); err != nil {
		t.Fatal(err)
	}
	if preservedMenus != 4 || clearedLinks != 2 || validLink != 7 {
		t.Fatalf("menu repair: rows=%d cleared=%d valid variant=%d", preservedMenus, clearedLinks, validLink)
	}
	_, badLinkErr := conn.Exec(ctx, "INSERT INTO menu_items (product_variant_id) VALUES (999)")
	var foreignKeyError *pgconn.PgError
	if !errors.As(badLinkErr, &foreignKeyError) || foreignKeyError.Code != "23503" {
		t.Fatalf("restored menu foreign key must remain enforced: %v", badLinkErr)
	}
	migration, err := os.ReadFile(filepath.Join("..", "migrations", "20261102130000_rename_biometrics_enroll_permission.sql"))
	if err != nil {
		t.Fatal(err)
	}
	for i := 0; i < 2; i++ {
		if _, err := conn.Exec(ctx, string(migration)); err != nil {
			t.Fatalf("permission migration attempt %d: %v", i+1, err)
		}
	}
	var grantCount int
	if err := conn.QueryRow(ctx, "SELECT count(*) FROM role_permissions rp JOIN permissions p ON p.id = rp.permission_id WHERE p.code = 'users:enroll'").Scan(&grantCount); err != nil {
		t.Fatal(err)
	}
	if grantCount != 2 {
		t.Fatalf("got %d biometric grants; want 2", grantCount)
	}
	// A second repair must also preserve counters that are already ahead.
	if err := repairRestoredSequences(ctx, conn); err != nil {
		t.Fatal(err)
	}
	checks := []struct {
		query string
		want  int64
	}{
		{"SELECT nextval('empty_rows_id_seq')", 1},
		{"SELECT nextval('ahead_rows_id_seq')", 101},
		{"INSERT INTO equal_rows DEFAULT VALUES RETURNING id", 2},
		{"INSERT INTO staging.identity_rows DEFAULT VALUES RETURNING row_number", 41},
		{`INSERT INTO "Odd table" DEFAULT VALUES RETURNING "Odd ID"`, 13},
	}
	for _, check := range checks {
		var got int64
		if err := conn.QueryRow(ctx, check.query).Scan(&got); err != nil {
			t.Fatal(err)
		}
		if got != check.want {
			t.Errorf("%s returned %d; want %d", check.query, got, check.want)
		}
	}
	var permissionCounter int64
	if err := conn.QueryRow(ctx, "SELECT last_value FROM permissions_id_seq").Scan(&permissionCounter); err != nil {
		t.Fatal(err)
	}
	if permissionCounter < 500 {
		t.Fatalf("permission sequence moved backwards: %d", permissionCounter)
	}
}

func newRestoreTestDatabase(t *testing.T) (context.Context, *url.URL, *pgx.ConnConfig) {
	t.Helper()
	dsn := os.Getenv("NEMBUS_RESTORE_TEST_DSN")
	if dsn == "" {
		t.Skip("set NEMBUS_RESTORE_TEST_DSN to a PostgreSQL admin connection for integration testing")
	}
	testURL, err := url.Parse(dsn)
	if err != nil || (testURL.Scheme != "postgres" && testURL.Scheme != "postgresql") {
		t.Fatal("NEMBUS_RESTORE_TEST_DSN must be a postgres:// or postgresql:// URL")
	}
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Minute)
	t.Cleanup(cancel)
	admin, err := pgx.Connect(ctx, dsn)
	if err != nil {
		t.Fatal(err)
	}
	dbName := fmt.Sprintf("restore_sequence_test_%d", time.Now().UnixNano())
	quotedDB := pgx.Identifier{dbName}.Sanitize()
	if _, err := admin.Exec(ctx, "CREATE DATABASE "+quotedDB); err != nil {
		admin.Close(ctx)
		t.Fatal(err)
	}
	t.Cleanup(func() {
		cleanupCtx, cleanupCancel := context.WithTimeout(context.Background(), 15*time.Second)
		defer cleanupCancel()
		defer admin.Close(cleanupCtx)
		if _, err := admin.Exec(cleanupCtx, "DROP DATABASE "+quotedDB+" WITH (FORCE)"); err != nil {
			t.Errorf("clean up disposable database: %v", err)
		}
	})
	testURL.Path = "/" + dbName
	testURL.RawPath = ""
	query := testURL.Query()
	query.Del("dbname")
	query.Del("database")
	testURL.RawQuery = query.Encode()
	config, err := pgx.ParseConfig(testURL.String())
	if err != nil {
		t.Fatal(err)
	}
	if config.Database != dbName {
		t.Fatal("test connection must target the disposable database")
	}

	return ctx, testURL, config
}

func TestRestoreTenantBackupTwice(t *testing.T) {
	backup := os.Getenv("NEMBUS_RESTORE_BACKUP_FILE")
	if backup == "" {
		t.Skip("set NEMBUS_RESTORE_BACKUP_FILE to test a full tenant dump")
	}
	ctx, testURL, config := newRestoreTestDatabase(t)
	conn, err := pgx.ConnectConfig(ctx, config)
	if err != nil {
		t.Fatal(err)
	}
	defer conn.Close(ctx)
	// Reproduce a retry where provider objects survived an earlier failure.
	_, err = conn.Exec(ctx, `CREATE SCHEMA _avnadmin_monitor;
CREATE FUNCTION _avnadmin_monitor.explain_statement(text) RETURNS integer LANGUAGE SQL AS 'SELECT 1';
CREATE SCHEMA atlas_schema_revisions;
CREATE TABLE atlas_schema_revisions.atlas_schema_revisions (version TEXT PRIMARY KEY);
INSERT INTO atlas_schema_revisions.atlas_schema_revisions VALUES ('local-sentinel');`)
	if err != nil {
		t.Fatal(err)
	}
	for attempt := 1; attempt <= 2; attempt++ {
		if err := restoreSQL(backup, testURL.String()); err != nil {
			t.Fatalf("full backup restore attempt %d: %v", attempt, err)
		}
		var sentinel, revisions int
		if err := conn.QueryRow(ctx, "SELECT _avnadmin_monitor.explain_statement('test')").Scan(&sentinel); err != nil {
			t.Fatal(err)
		}
		if err := conn.QueryRow(ctx, "SELECT count(*) FROM atlas_schema_revisions.atlas_schema_revisions WHERE version = 'local-sentinel'").Scan(&revisions); err != nil {
			t.Fatal(err)
		}
		if sentinel != 1 || revisions != 1 {
			t.Fatal("restore changed administrative objects outside application schemas")
		}
	}
}
